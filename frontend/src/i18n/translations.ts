/** Reads one string, falling back to English, then the key itself. */
export function translate(lang: Lang, namespace: string, key: string): string {
  const ns = translations[namespace];
  if (!ns) return key;
  return ns[lang]?.[key] ?? ns.en[key] ?? key;
}
